'use strict';
// A fixed, one-ply opponent. It never reads or changes learning profiles.
let cpuTimer=null;
function isCpuTurn(){return mode==='cpu'&&active===1&&phase!=='over'}
function cancelCpu(){if(cpuTimer!==null)clearTimeout(cpuTimer);cpuTimer=null}
function scheduleCpu(){cancelCpu();if(isCpuTurn())cpuTimer=setTimeout(()=>{cpuTimer=null;cpuTurn()},350)}
function cpuFeatureValue(pos,target){
 if(target.type==='monastery'){
  const [x,y]=pos.split(',').map(Number);let nearby=0;
  for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++)if((dx||dy)&&board.has(k(x+dx,y+dy)))nearby++;
  return 1.8+nearby*.65;
 }
 const type=target.type,nodes=makeGraph(type),comp=component(nodes,nodeId(pos,type,target.n));
 const size=new Set(comp.map(n=>n.pos)).size;
 if(type==='field'){
  if(stock[1]<4||round<18)return -Infinity;
  const cities=cityFeatures().results.filter(c=>c.complete),touching=new Set();
  for(const f of comp)for(const c of cities)if(c.members.some(n=>fieldTouchesCity(f,n)))touching.add(c.key);
  return touching.size*2.6-1.5+(round>55?1:0);
 }
 const complete=featureComplete(comp,type);
 const shields=type==='city'?[...new Set(comp.map(n=>n.pos))].reduce((s,p)=>s+(db.get(board.get(p).id).shieldCountPerPhysicalTile||0),0):0;
 if(complete)return (size+shields)*(type==='city'?2:1)+2;
 return (type==='city'?2:1.1)+Math.min(size,8)*.45-(stock[1]<=2?2:0);
}
function chooseCpuTarget(pos){
 const targets=targetState(pos).filter(t=>t.enabled);let best=null,value=0.8;
 for(const t of targets){const v=cpuFeatureValue(pos,t);if(v>value){value=v;best=t}}
 return best;
}
function chooseCpuPlacement(){
 const options=optionsFor(selected);let best=null,bestValue=-Infinity;
 // Bound search work on mobile. All candidates are generated by the shared rules.
 const stride=Math.max(1,Math.ceil(options.length/24));
 for(let i=0;i<options.length;i+=stride){
  const o=options[i],pos=k(o.x,o.y);board.set(pos,{id:selected.id,rot:o.r,meeple:null});
  try{
   let value=0;
   for(let d=0;d<4;d++)if(board.has(nk(o.x,o.y,d)))value+=.15;
   for(const type of ['city','road']){
    const nodes=makeGraph(type),seen=new Set();
    for(let n=0;n<getComponents(selected,type).length;n++){
     const start=nodeId(pos,type,n);if(seen.has(start))continue;
     const comp=component(nodes,start);comp.forEach(v=>seen.add(nodeId(v.pos,type,v.n)));
     const owners=[0,0];for(const v of comp)if(v.v.meeple?.type===type&&v.v.meeple.n===v.n)owners[v.v.meeple.player]++;
     if(!owners[0]&&!owners[1])continue;
     const size=new Set(comp.map(v=>v.pos)).size;
     const weight=featureComplete(comp,type)?(type==='city'?2:1)*size: .4;
     value+=weight*((owners[1]>=owners[0]?1:0)-(owners[0]>=owners[1]?1:0));
    }
   }
   const t=chooseCpuTarget(pos);if(t)value+=cpuFeatureValue(pos,t)*.55;
   if(value>bestValue){bestValue=value;best=o}
  }finally{board.delete(pos)}
 }
 return best;
}
function cpuTurn(){
 if(!isCpuTurn())return;
 if(phase==='tile'){
  const move=chooseCpuPlacement();if(!move)return;
  rot=move.r;placeTile(move.x,move.y,true);
 }
 if(phase==='meeple'){
  const target=chooseCpuTarget(placed);
  if(target)confirmTarget(target,true);else finish(null);
 }
}
